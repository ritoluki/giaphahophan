import { describe, expect, it } from "vitest";
import { mfaQrImageSource } from "./mfa-qr";

const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16"><path fill="#000" d="M0 0h16v16H0z"/></svg>';
describe("MFA QR source", () => {
  it("supports the Auth provider XML declaration and SVG doctype", () => {
    const document = `<?xml version="1.0" encoding="UTF-8"?>\n<!-- QR generated by provider -->\n<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">\n${svg}`;
    expect(decodeURIComponent(mfaQrImageSource(`data:image/svg+xml;utf-8,${document}`).split(",")[1]!)).toBe(document);
  });
  it.each([svg, `data:image/svg+xml;utf-8,${svg}`, `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`, `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`])("preserves a single complete SVG image", (value) => {
    const source = mfaQrImageSource(value);
    expect(decodeURIComponent(source.slice(source.indexOf(",") + 1))).toBe(svg);
    expect(source).not.toContain("data:image/svg+xml;utf-8,");
    expect(source).not.toContain("#000");
  });
  it.each(["https://example.invalid/image.svg", "javascript:alert(1)", "data:text/html,<script></script>", "data:image/svg+xml;utf8,%broken"])("rejects unsupported or malformed image source", (value) => {
    expect(() => mfaQrImageSource(value)).toThrow("Mã QR chưa hợp lệ");
  });
});
